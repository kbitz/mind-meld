def live(path="memory.md", content=b"abc", source="claude", vv=None, held=None):
    meta = {
        "source": source,
        "path": path,
        "vv": {DEVICE: 1} if vv is None else vv,
        "sha": hashlib.sha256(content).hexdigest(),
        "size": len(content),
        "mtime": 1.5,
        "deleted": False,
    }
    if held is not None:
        meta["held"] = held
    return store_format.Entry(meta, content)


def tombstone(path="gone.md", vv=None, held=None):
    meta = {
        "source": "claude",
        "path": path,
        "vv": {DEVICE: 1} if vv is None else vv,
        "sha": None,
        "size": 0,
        "mtime": None,
        "deleted": True,
    }
    if held is not None:
        meta["held"] = held
    return store_format.Entry(meta)


def frame(raw):
    return struct.pack(">I", len(raw)) + raw


def independent_payload(hdr, entries):
    frames = [frame(json_bytes(hdr))]
    for entry in entries:
        frames.append(frame(json_bytes(entry.metadata)))
        if entry.content is not None:
            frames.append(frame(entry.content))
    return b"".join(frames)


