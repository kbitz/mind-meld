def context(keys, kind="commit", seq=1, part=1, nparts=1):
    return envelope.RecordContext(keys.fleet_id, DEVICE, kind, seq, part, nparts)


def independent_subkey(master, fleet_id, kind):
    # HKDF extract+expand implemented with stdlib HMAC, not the production HKDF call.
    prk = hmac.digest(bytes.fromhex(fleet_id), master, "sha256")
    return hmac.digest(prk, b"mm-store-v3/" + kind.encode() + b"\x01", "sha256")


def authentic_compressed(compressed, keys, expected):
    key = independent_subkey(keys.master_key, keys.fleet_id, expected.kind)
    aad = b"mm-record-v3\0" + json_bytes(
        [
            expected.fleet_id,
            expected.device_id,
            expected.kind,
            expected.seq,
            expected.part,
            expected.nparts,
        ]
    )
    return b"\x03" + NONCE + AESGCM(key).encrypt(NONCE, compressed, aad)


class TestFleet71C:
    def test_t01_independent_fleet_hkdf_keycheck_vectors(self, monkeypatch):
        random_values = iter([bytes.fromhex(FLEET), SALT, NONCE])
        monkeypatch.setattr(envelope.os, "urandom", lambda n: next(random_values))
        data, keys = envelope.create_fleet(PASSWORD, created_at=STAMP, memory_kb=1024, time_cost=1)
        header = json.loads(data)
        assert keys.master_key.hex() == MASTER_HEX
        assert keys.commit_key.hex() == COMMIT_KEY_HEX
        assert keys.commit_key == independent_subkey(keys.master_key, FLEET, "commit")
        # Pin every domain by name: a reordered derivation tuple must not pass.
        for kind in ("commit", "snapshot", "presence", "keycheck"):
            assert getattr(keys, f"{kind}_key") == independent_subkey(
                bytes.fromhex(MASTER_HEX), FLEET, kind
            )
        assert base64.b64decode(header["keycheck"]).hex() == KEYCHECK_HEX
        assert data == json_bytes(header)
        assert (
            b"mm-fleet-v3\0" + json_bytes({k: v for k, v in header.items() if k != "keycheck"})
            == FLEET_AAD
        )
        independent_key = independent_subkey(keys.master_key, FLEET, "keycheck")
        fixture = bytes.fromhex(KEYCHECK_HEX)
        assert (
            gzip.decompress(AESGCM(independent_key).decrypt(fixture[1:13], fixture[13:], FLEET_AAD))
            == b"mm-keycheck-v3"
        )
        # Fixture reads do not depend on our writer.
        header["keycheck"] = base64.b64encode(fixture).decode()
        assert envelope.unlock_fleet(json_bytes(header), PASSWORD) == keys
        reordered = json.dumps(header, indent=2).encode()
        assert envelope.unlock_fleet(reordered, PASSWORD) == keys
        assert keys.created_at == STAMP
        assert (keys.memory_kb, keys.time_cost, keys.parallelism, keys.salt) == (1024, 1, 1, SALT)

