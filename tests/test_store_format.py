def json_bytes(value):
    """Independent fixture serialization; production helpers are never used here."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def assert_error(category, fn, *args, **kwargs):
    with pytest.raises(envelope.StoreError) as caught:
        fn(*args, **kwargs)
    assert caught.value.category == category
    assert "docs/invariants/store.md#errors" in str(caught.value)
    assert PASSWORD not in str(caught.value)
    assert "\x1b" not in str(caught.value)
    return caught.value


