    def test_t09_frame_aligned_hybrid_and_forged_digest(self, keys):
        expected, prefix = payload_at_length(keys, store_format.MAX_PART_BYTES)
        first = store_format.decode_commit(prefix, expected=expected).entries[0]
        hdr = header(expected, 2)
        a = store_format.encode_commit(hdr, [first, live("tail", b"aaa")], expected=expected)
        b = store_format.encode_commit(hdr, [first, live("tail", b"bbb")], expected=expected)
        assert a[: store_format.MAX_PART_BYTES] == b[: store_format.MAX_PART_BYTES]
        assert a[store_format.MAX_PART_BYTES :][:1] == b"\0"  # starts at metadata frame prefix
        a_parts = list(store_format.seal_record(a, keys, expected=expected))
        b_parts = list(store_format.seal_record(b, keys, expected=expected))
        hybrid = a[: store_format.MAX_PART_BYTES] + b[store_format.MAX_PART_BYTES :]
        assert store_format.decode_commit(hybrid, expected=expected).entries[-1].content == b"bbb"
        assert_error(
            "invalid_parts",
            store_format.open_record,
            [a_parts[0], b_parts[1]],
            keys,
            expected=expected,
        )
        forged = sealed_wrapper(
            keys,
            b_parts[1][0],
            hashlib.sha256(a).digest(),
            len(a),
            b[store_format.MAX_PART_BYTES :],
        )
        assert_error(
            "invalid_parts", store_format.open_record, [a_parts[0], forged], keys, expected=expected
        )
        assert store_format.open_record(b_parts, keys, expected=expected) == b
        # A complete authentic replacement at the same slot is accepted, not detected as stale.
        assert store_format.open_record(a_parts, keys, expected=expected) == a

    def test_t10_bounded_counts_and_4gib_claim_without_allocation(self, keys, monkeypatch):
        expected = context(keys)
        for count in (513, 10**1000):
            assert_error(
                "resource_limit",
                store_format.open_record,
                [],
                keys,
                expected=expected,
                nparts=count,
            )
        for count in (0, True, 1.0):
            assert_error(
                "invalid_parts", store_format.open_record, [], keys, expected=expected, nparts=count
            )
        # Exactly 4GiB is an allowed claim: one actual 8MiB part, 511 absent; no 4GiB buffer.
        full = replace(expected, nparts=512)
        accepted = sealed_wrapper(keys, full, bytes(32), 2**32, bytes(store_format.MAX_PART_BYTES))
        result = store_format.open_record([accepted], keys, expected=expected)
        assert result == store_format.IncompleteParts(tuple(range(2, 513)), 512)
        over = sealed_wrapper(keys, full, bytes(32), 2**32 + 1, b"")
        assert_error("resource_limit", store_format.open_record, [over], keys, expected=expected)
        malformed = sealed_wrapper(keys, replace(expected, nparts=2), bytes(32), 1, b"x")
        assert_error(
            "invalid_parts", store_format.open_record, [malformed], keys, expected=expected
        )
        # Legal envelopes with short chunks are not legal multipart records, even while incomplete.
        short = sealed_wrapper(
            keys, replace(expected, nparts=2), bytes(32), store_format.MAX_PART_BYTES + 1, b"x"
        )
        assert_error("invalid_parts", store_format.open_record, [short], keys, expected=expected)
        # Known impossible counts are rejected before any decrypt or enumeration.
        monkeypatch.setattr(envelope, "open_part", lambda *a, **k: pytest.fail("decrypt"))
        assert_error(
            "resource_limit",
            store_format.open_record,
            [accepted],
            keys,
            expected=expected,
            nparts=513,
        )

