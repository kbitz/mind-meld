def payload_at_length(keys, length, *, random_content=False, kind="commit", seq=1):
    """Real framed record of exact logical length; frame overhead is computed independently."""
    expected = context(keys, kind, seq)
    hdr = header(expected, 1)
    meta = live().metadata.copy()
    size = length
    for _ in range(5):
        meta["size"] = size
        size = length - (4 + len(json_bytes(hdr)) + 4 + len(json_bytes(meta)) + 4)
    content = os.urandom(size) if random_content else bytes(size)
    meta.update(size=size, sha=hashlib.sha256(content).hexdigest())
    encode = store_format.encode_commit if kind == "commit" else store_format.encode_snapshot
    payload = encode(hdr, [store_format.Entry(meta, content)], expected=expected)
    assert len(payload) == length
    return expected, payload


