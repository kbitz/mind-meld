def named_parts(parts, keys):
    """Reader obtains expected identity solely from canonical names and verified fleet."""
    result = []
    for full_context, sealed in parts:
        key = layout.record_key(
            full_context.device_id,
            full_context.kind,
            full_context.seq,
            part=full_context.part,
            nparts=full_context.nparts,
        )
        name = layout.parse_record_key(key)
        result.append(
            (
                envelope.RecordContext(
                    keys.fleet_id, name.device_id, name.kind, name.seq, name.part, name.nparts
                ),
                sealed,
            )
        )
    return result


def test_t16_seal_record_refuses_before_yielding(keys):
    anchor = context(keys)
    valid = store_format.encode_commit(header(anchor), [], expected=anchor)
    cases = [
        (b"\x00\x00\x00\x02{}", anchor, keys, "invalid_payload"),
        (valid, replace(anchor, seq=2), keys, "invalid_payload"),
        (valid, replace(anchor, nparts=2), keys, "invalid_parts"),
        (valid, anchor, replace(keys, fleet_id="f" * 32), "authentication"),
    ]
    for payload, expected, fleet_keys, category in cases:
        # Lazy generator: the first next() must refuse before any part is yielded.
        sealed = store_format.seal_record(payload, fleet_keys, expected=expected)
        assert_error(category, next, sealed)
    presence_context = context(keys, "presence", 0)
    oversized = bytes(envelope.MAX_PRESENCE_BYTES + envelope.PART_WRAPPER_BYTES + 1)
    assert_error("resource_limit", envelope.seal_part, oversized, keys, expected=presence_context)


def test_t16_full_caller_flow_and_multipart_snapshot(fleet):
    keys = envelope.unlock_fleet(fleet[0], PASSWORD)
    expected = context(keys)
    entries = [live()]
    payload = store_format.encode_commit(header(expected, 1), entries, expected=expected)
    supplied = named_parts(store_format.seal_record(payload, keys, expected=expected), keys)
    opened = store_format.open_record(supplied, keys, expected=expected)
    assert store_format.decode_commit(opened, expected=expected).entries == tuple(entries)
    for changes in ({"seq": 2}, {"device_id": PEER}, {"kind": "snapshot"}):
        changed = replace(expected, **changes)
        moved = [(replace(full, **changes), data) for full, data in supplied]
        assert_error("authentication", store_format.open_record, moved, keys, expected=changed)
    snap, large = payload_at_length(keys, store_format.MAX_PART_BYTES, kind="snapshot", seq=0)
    first = store_format.decode_snapshot(large, expected=snap).entries[0]
    versions = [
        first,
        tombstone(),
        live("memory.md", b"held", vv={PEER: 1}, held=True),
        tombstone("memory.md", vv={PEER: 2}, held=True),
    ]
    payload = store_format.encode_snapshot(header(snap, len(versions)), versions, expected=snap)
    supplied = named_parts(store_format.seal_record(payload, keys, expected=snap), keys)
    assert len(supplied) == 2
    assert store_format.open_record(supplied[:1], keys, expected=snap) == (
        store_format.IncompleteParts((2,), 2)
    )
    opened = store_format.open_record(reversed(supplied), keys, expected=snap)
    assert store_format.decode_snapshot(opened, expected=snap).entries == tuple(versions)
