        assert len(parts) == count
        for index, (full_context, sealed) in enumerate(parts, 1):
            assert (full_context.part, full_context.nparts) == (index, count)
            plain = envelope.open_part(sealed, keys, expected=full_context)
            assert plain[:32] == hashlib.sha256(payload).digest()
            assert struct.unpack_from(">Q", plain, 32)[0] == length
            assert (
                plain[40:]
                == payload[
                    (index - 1) * store_format.MAX_PART_BYTES : index * store_format.MAX_PART_BYTES
                ]
            )
        assert store_format.open_record(reversed(parts), keys, expected=expected) == payload

