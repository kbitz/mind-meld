def test_t15_legacy_and_explicit_v3_coexist():
    legacy = crypto.encrypt(b"legacy synthetic", PASSWORD, 1024)
    session_before = crypto._SESSION.copy()
    cache_before = crypto._MASTER_KEY_CACHE.copy()
    # Snapshot legacy state before create as well as unlock, seal and open.
    data, created = envelope.create_fleet(PASSWORD, created_at=STAMP, memory_kb=1024, time_cost=1)
    keys = envelope.unlock_fleet(data, PASSWORD)
    assert keys == created
    expected = context(keys)
    sealed = envelope.seal_part(b"new synthetic", keys, expected=expected)
    assert envelope.open_part(sealed, keys, expected=expected) == b"new synthetic"
    assert crypto._SESSION == session_before and crypto._MASTER_KEY_CACHE == cache_before
    assert (
        crypto.FORMAT_VERSION == 2 and crypto.decrypt(legacy, PASSWORD, 1024) == b"legacy synthetic"
    )
    with pytest.raises(NewerFormatError):
        crypto.decrypt(sealed, PASSWORD, 1024)
    assert crypto._parse_crypto_init(sealed).newer_version == 3


